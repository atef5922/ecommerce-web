export function getProductBySlug(slug: string) {
  return catalogProducts.find((product) => product.slug === slug || product.id === slug);
}

export function getRelatedProducts(product: Product, limit = 4) {
  return catalogProducts
    .filter((candidate) => candidate.id !== product.id)
    .sort((a, b) => {
      const scoreProduct = (candidate: Product) =>
        Number(candidate.category === product.category) * 5 +
        Number(candidate.brand === product.brand) * 3 +
        Number(candidate.color === product.color) * 2 +
        Number(candidate.size === product.size) +
        Number(candidate.isPopular === product.isPopular) +
        Number(candidate.monthlyDeal === product.monthlyDeal);
      const aScore = scoreProduct(a);
      const bScore = scoreProduct(b);

      if (aScore === bScore) {
        return (b.reviewCount ?? 0) - (a.reviewCount ?? 0);
      }

      return bScore - aScore;
    })
    .slice(0, limit);
}
